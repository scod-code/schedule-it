"""
Export a solved ScheduleResult to:
  - PDF  (via ReportLab)
  - CSV  (stdlib csv)
  - ICS  (one file per team, using icalendar)

All functions return bytes so they can be streamed directly from FastAPI responses
or written to disk.
"""
from __future__ import annotations

import csv
import io
import uuid
from datetime import datetime, timezone
from typing import Dict, List

from icalendar import Calendar, Event  # type: ignore
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .models import MatchResult, ScheduleResult


# ---------------------------------------------------------------------------
# PDF
# ---------------------------------------------------------------------------

def to_pdf(result: ScheduleResult) -> bytes:
    """Render the full fixture list as a PDF and return the raw bytes."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=2 * cm,
        leftMargin=2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
    )
    styles = getSampleStyleSheet()
    story = []

    # Title
    story.append(Paragraph(result.league_name, styles["Title"]))
    story.append(Spacer(1, 0.5 * cm))

    # Metrics
    m = result.metrics
    meta_lines = [
        f"Fixtures: {len(result.matches)}",
        f"Home/Away breaks: {m.home_away_breaks}",
        f"Balance score: {m.balance_score:.2f}",
        f"Generated by Schedule-it — schedule-it.app",
    ]
    for line in meta_lines:
        story.append(Paragraph(line, styles["Normal"]))
    story.append(Spacer(1, 0.5 * cm))

    # Table
    headers = ["Date", "Slot", "Home", "Away", "Venue"]
    rows = [headers] + [
        [fix.slot_date, fix.slot_label, fix.home_team, fix.away_team, fix.venue]
        for fix in result.matches
    ]

    col_widths = [2.8 * cm, 3.5 * cm, 4 * cm, 4 * cm, 3.5 * cm]
    tbl = Table(rows, colWidths=col_widths, repeatRows=1)
    tbl.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a56db")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f3f4f6")]),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    story.append(tbl)

    doc.build(story)
    return buffer.getvalue()


# ---------------------------------------------------------------------------
# CSV
# ---------------------------------------------------------------------------

def to_csv(result: ScheduleResult) -> bytes:
    """Return the fixture list as UTF-8 CSV bytes."""
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["date", "slot", "home_team", "away_team", "venue"])
    for fix in result.matches:
        writer.writerow([fix.slot_date, fix.slot_label, fix.home_team, fix.away_team, fix.venue])
    return output.getvalue().encode("utf-8")


# ---------------------------------------------------------------------------
# ICS — one calendar per team
# ---------------------------------------------------------------------------

def _parse_date(date_str: str) -> datetime:
    """Parse an ISO date string like '2025-09-06' into a naive datetime."""
    return datetime.strptime(date_str, "%Y-%m-%d")


def to_ics_per_team(result: ScheduleResult) -> Dict[str, bytes]:
    """
    Return a dict mapping team name → ICS bytes containing only that team's fixtures.
    """
    # Group matches by team
    team_matches: Dict[str, List[MatchResult]] = {}
    for fix in result.matches:
        team_matches.setdefault(fix.home_team, []).append(fix)
        team_matches.setdefault(fix.away_team, []).append(fix)

    calendars: Dict[str, bytes] = {}
    for team_name, matches in team_matches.items():
        cal = Calendar()
        cal.add("prodid", f"-//Schedule-it//{result.league_name}//EN")
        cal.add("version", "2.0")
        cal.add("calscale", "GREGORIAN")
        cal.add("x-wr-calname", f"{team_name} – {result.league_name}")

        for fix in matches:
            event = Event()
            dt = _parse_date(fix.slot_date)
            home_away = "vs" if fix.home_team == team_name else "@"
            opponent = fix.away_team if fix.home_team == team_name else fix.home_team
            summary = f"{team_name} {home_away} {opponent}"

            event.add("summary", summary)
            event.add("dtstart", dt.date())
            event.add("dtend", dt.date())
            event.add("location", fix.venue)
            event.add(
                "description",
                f"{fix.home_team} vs {fix.away_team}\nVenue: {fix.venue}\nSlot: {fix.slot_label}\n\nMade with Schedule-it — schedule-it.app",
            )
            event["uid"] = str(uuid.uuid4())
            cal.add_component(event)

        calendars[team_name] = cal.to_ical()

    return calendars
